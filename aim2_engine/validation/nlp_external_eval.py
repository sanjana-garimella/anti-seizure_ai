"""
validation/nlp_external_eval.py
---------------------------------
Tests the point-A structurers against a REAL, externally-authored, published
NLP benchmark - not text generated by this assistant. Closes the "echo
chamber" problem flagged repeatedly elsewhere in validation/: every synthetic
eval so far (nlp_synthetic_eval.py, nlp_synthetic_eval_large.py,
nlp_finetune_compare.py) tested each structurer against phrasing built from
its own or a closely related keyword/phrase bank, which inflates scores and
can't reveal real generalization gaps.

DATASET: ADE-Corpus-V2 (Gurulingappa et al. 2012, J. Biomedical Informatics),
distributed publicly via HuggingFace `datasets`
(ade-benchmark-corpus/ade_corpus_v2, config Ade_corpus_v2_drug_ade_relation).
Built from MEDLINE case-report abstracts, double-annotated by the original
authors with character-level drug + adverse-effect spans. Real, externally
authored, expert-labeled - genuinely independent of anything in this repo.

IMPORTANT CAVEATS - read before trusting the numbers:
  1. This is FORMAL clinical/research-literature language ("ototoxicity",
     "myelosuppression", "agranulocytosis"), not colloquial caregiver speech.
     A structurer doing well here does not mean it would do well on a
     parent's free-text answer - that still needs real-ish caregiver
     examples nobody has supplied yet (see nlp_synthetic_eval.py docstring).
  2. NOT epilepsy-specific. Most rows are about unrelated drugs
     (antipsychotics, NSAIDs, insulin, chemo agents, etc.) and unrelated
     adverse effects. A second pass below filters to the epilepsy-adjacent
     slice (seizure-related effects, or one of the 11 study ASM names) for a
     more topically relevant (but much smaller) sample.
  3. Scoring is per-example, multi-label, coarse-grained: "did the
     structurer find >=1 DRUG finding and >=1 SIDE_EFFECT finding", same
     convention as nlp_finetune_compare.py's coarse comparison - NOT exact
     character-span matching, which would be noisy against differently
     tokenized model outputs and isn't how any other script here scores.

REQUIRES: pip3 install --user datasets
  (separate from transformers/torch - this just downloads/reads the public
  benchmark; clinic.py itself never needs the `datasets` library)

DECISION-PATH NOTE: advisory/diagnostic only, same as every script in this
directory. Does not touch engine_core.

Run:
  cd aim2_engine
  python3 validation/nlp_external_eval.py
  python3 validation/nlp_external_eval.py --n 1000 --transformer-sample 300
  python3 validation/nlp_external_eval.py --no-transformers     # lexicon only, fast
"""
from __future__ import annotations

import argparse
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from nlp.structurer import _DRUG_NAMES   # the 11 study ASMs + brand names
from validation.nlp_eval_stats import (
    bootstrap_ci, mcnemars_test, fmt_ci, write_artifact)

_ASM_NAMES = {n.lower() for n in _DRUG_NAMES}
_SEIZURE_WORDS = ("seizure", "convuls", "epilep", "status epilepticus")


def _coarse_labels(finding) -> str:
    if finding.field == "side_effect":
        return "SIDE_EFFECT"
    return {"seizure_mention": "SEIZURE", "drug_mention": "DRUG",
            "test_mention": "TEST"}.get(finding.field)


def load_rows(n: int, seed: int):
    try:
        from datasets import load_dataset
    except ImportError:
        print("  `datasets` not installed. Run: pip3 install --user datasets")
        sys.exit(1)
    ds = load_dataset(
        "ade-benchmark-corpus/ade_corpus_v2",
        "Ade_corpus_v2_drug_ade_relation",
        revision="4ba01c71687dd7c996597042449448ea312126cf",
    )["train"]
    idx = list(range(len(ds)))
    random.Random(seed).shuffle(idx)
    rows = [ds[i] for i in idx[:n]]
    return rows


def is_epilepsy_adjacent(row) -> bool:
    text = row["text"].lower()
    drug = (row.get("drug") or "").lower()
    effect = (row.get("effect") or "").lower()
    return (drug in _ASM_NAMES
            or any(w in effect for w in _SEIZURE_WORDS)
            or any(w in text for w in _SEIZURE_WORDS))


# HONEST-FRAMING CAVEAT (finding D2): in this config gold is hardcoded to
# {DRUG, SIDE_EFFECT} for EVERY row, so nothing here can be a false positive on
# these two classes by construction. That means PRECISION IS STRUCTURALLY NOT
# MEASURABLE in this setup — a model that over-fires DRUG/SIDE_EFFECT on every
# row scores perfectly. Treat the reported "precision"/"F1" as a RECALL PROXY
# only. A real precision number needs per-span gold, which this scoring does not
# use.
_PRECISION_CAVEAT = (
    "    CAVEAT: gold is {DRUG,SIDE_EFFECT} for every row by construction, so "
    "no false\n    positive on these classes is possible here — 'precision'/'F1' "
    "below are NOT\n    measurable precision; they are a RECALL PROXY. An "
    "over-firing model looks perfect.")


def evaluate(name, structurer, rows, max_examples_shown=10):
    tp = fp = fn = 0
    mismatches = []
    per_example_correct = []   # 1.0 if the row got BOTH gold labels (recall proxy)
    for row in rows:
        text = row["text"]
        gold = {"DRUG", "SIDE_EFFECT"}      # every row in this config has both by construction
        try:
            findings = structurer.structure(text, source_question="Q13")
        except Exception as exc:
            print(f"    ! {name} raised on {text!r}: {exc}")
            findings = []
        pred = {c for c in (_coarse_labels(f) for f in findings) if c}
        ex_tp, ex_fp, ex_fn = gold & pred, pred - gold, gold - pred
        tp += len(ex_tp); fp += len(ex_fp); fn += len(ex_fn)
        per_example_correct.append(1.0 if gold <= pred else 0.0)
        if (ex_fp or ex_fn) and len(mismatches) < max_examples_shown:
            mismatches.append((text, row.get("drug"), row.get("effect"), sorted(pred)))

    precision = tp / (tp + fp) if (tp + fp) else float("nan")
    recall = tp / (tp + fn) if (tp + fn) else float("nan")
    f1 = (2 * precision * recall / (precision + recall)
          if precision == precision and recall == recall and (precision + recall)
          else float("nan"))
    # Per-example "both-labels-found" rate with a bootstrap 95% CI so a small-n
    # margin between models can be read honestly (finding D2).
    rate, lo, hi = bootstrap_ci(per_example_correct)
    print(f"\n  === {name}  (n={len(rows)}) ===")
    print(_PRECISION_CAVEAT)
    print(f"    recall-proxy (both labels found per row): {fmt_ci(rate, lo, hi)}")
    print(f"    [recall-proxy] precision {precision:.3f}  recall {recall:.3f}  "
          f"F1 {f1:.3f}  (tp={tp} fp={fp} fn={fn})")
    if mismatches:
        print(f"    sample misses (up to {max_examples_shown}):")
        for text, drug, effect, pred in mismatches:
            print(f"      {text!r}\n        gold drug={drug!r} effect={effect!r}  predicted_types={pred}")
    return {"precision": precision, "recall": recall, "f1": f1,
            "recall_proxy_rate": rate, "recall_proxy_ci": [lo, hi],
            "n": len(rows), "per_example_correct": per_example_correct}


def _pairwise_significance(results):
    """McNemar's test on paired per-example correctness for every model pair
    that has aligned per-example data (finding D2). Prints n, discordant counts
    and p, so an A-vs-B claim is significance-tested rather than a bare delta."""
    keyed = {k: v for k, v in results.items() if v.get("per_example_correct")}
    keys = list(keyed)
    if len(keys) < 2:
        return []
    out = []
    print("\n    pairwise significance (McNemar on paired per-example "
          "recall-proxy correctness):")
    for i in range(len(keys)):
        for j in range(i + 1, len(keys)):
            a, b = keys[i], keys[j]
            ca, cb = keyed[a]["per_example_correct"], keyed[b]["per_example_correct"]
            if len(ca) != len(cb):
                continue  # different samples — not paired, skip
            mt = mcnemars_test([bool(x) for x in ca], [bool(x) for x in cb])
            verdict = ("SIGNIFICANT" if mt["p_value"] == mt["p_value"]
                       and mt["p_value"] < 0.05 else "not significant (p>=0.05)")
            print(f"      {a} vs {b}: n={len(ca)}  b={mt['b']} c={mt['c']}  "
                  f"p={mt['p_value']:.4f} ({mt['method']}) -> {verdict}")
            out.append({"a": a, "b": b, "n": len(ca), **mt, "verdict": verdict})
    return out


def run_suite(label, rows, skip_transformers):
    print(f"\n  ---- {label} (n={len(rows)}) ----")
    from nlp.structurer import LexiconStructurer
    results = {"lexicon": evaluate("LexiconStructurer", LexiconStructurer(), rows)}
    if skip_transformers:
        results["_significance"] = _pairwise_significance(results)
        return results
    try:
        from nlp.transformer_structurer import (
            BioBERTStructurer, ClinicalBERTStructurer, GenericNERAdapter)
    except ImportError:
        print("  transformers/torch not installed - skipping zero-shot models.")
        results["_significance"] = _pairwise_significance(results)
        return results
    for key, candidate in [
        ("biobert", BioBERTStructurer(lazy=False)),
        ("clinical_bert", ClinicalBERTStructurer(lazy=False)),
        ("d4data", GenericNERAdapter("d4data/biomedical-ner-all", lazy=False)),
        ("humadex", GenericNERAdapter("HUMADEX/english_medical_ner", lazy=False)),
    ]:
        if candidate.is_available():
            results[key] = evaluate(getattr(candidate, "model_name", key), candidate, rows)
        else:
            print(f"\n  {key} unavailable - skipping.")
    results["_significance"] = _pairwise_significance(results)
    return results


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n", type=int, default=1000, help="general random sample size")
    ap.add_argument("--transformer-sample", type=int, default=300,
                     help="subsample of --n used for the transformer models (cost control)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--no-transformers", action="store_true")
    args = ap.parse_args()

    print("\n  NLP external (real, non-synthetic) eval - ADE-Corpus-V2")
    print("  " + "=" * 78)
    print("  Read the module docstring before trusting these numbers - this is real")
    print("  text, but general medical-literature ADE text, not caregiver speech.\n")

    rows = load_rows(args.n, args.seed)
    epilepsy_rows = [r for r in rows if is_epilepsy_adjacent(r)]
    print(f"  loaded {len(rows)} real annotated rows; {len(epilepsy_rows)} are "
          f"epilepsy-adjacent (mention a study ASM or a seizure-related effect)")

    general_sample = rows[:args.transformer_sample]
    general_results = run_suite("GENERAL sample (random, all drug classes)",
                                general_sample, args.no_transformers)

    ep_results = None
    if epilepsy_rows:
        ep_sample = epilepsy_rows[:args.transformer_sample]
        ep_results = run_suite("EPILEPSY-ADJACENT slice", ep_sample, args.no_transformers)
    else:
        print("\n  (no epilepsy-adjacent rows found in this sample - try a larger --n)")

    # HONEST FRAMING (finding D2): state the framing in the eval OUTPUT itself so
    # nobody cites these numbers as a decisive model ranking.
    print("\n  " + "=" * 78)
    print("  HONEST FRAMING (read before citing any number above):")
    print("  - Gold is {DRUG,SIDE_EFFECT} for every row by construction, so PRECISION")
    print("    IS NOT MEASURABLE here; the headline is a RECALL PROXY only.")
    print("  - Any model-vs-model gap is reported with a McNemar p-value and a")
    print("    bootstrap 95% CI. A gap that is 'not significant' or whose CIs overlap")
    print("    is NOT evidence that one model beats another — do not pick a production")
    print("    default on it. The deterministic LexiconStructurer stays the default.")
    print("  - This is formal medical-literature ADE text, not caregiver speech.")

    def _artifact_payload(results):
        if not results:
            return None
        return {k: ({kk: vv for kk, vv in v.items() if kk != "per_example_correct"}
                    if isinstance(v, dict) else v)
                for k, v in results.items()}

    payload = {
        "eval": "nlp_external_eval (ADE-Corpus-V2)",
        "framing": "recall-proxy only; precision not measurable; gaps significance-tested",
        "args": {"n": args.n, "transformer_sample": args.transformer_sample,
                 "seed": args.seed, "no_transformers": args.no_transformers},
        "n_rows_loaded": len(rows), "n_epilepsy_adjacent": len(epilepsy_rows),
        "general_sample": _artifact_payload(general_results),
        "epilepsy_adjacent": _artifact_payload(ep_results),
    }
    path = write_artifact("nlp_external_eval_result", payload)
    print(f"\n  Wrote reproducible result artifact: {path}")


if __name__ == "__main__":
    main()
