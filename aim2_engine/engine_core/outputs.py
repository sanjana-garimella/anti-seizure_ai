def _cadence(band, decision, faster_days_global=None) -> Dict[str, Any]:
    """Return the {interval label} for the recommended pace, using ONLY clinician
    values. Faster = the clinician's faster cadence (band-specific, else the
    global titration-config value); slower = slower_uptitration_interval_weeks;
    else the standard interval. Never invents a multiplier - if a pace-specific
    value is missing, it says so."""
    weeks = band.uptitration_interval_weeks or band.standard_uptitration_interval_weeks
    pace = decision.pace
    if pace == "faster":
        days = band.faster_uptitration_interval_days or faster_days_global
        if days:
            return {"pace": "faster", "every_days": days,
                    "label": f"every {days} days (faster cadence)"}
        return {"pace": "faster", "every_weeks": weeks,
                "label": f"every {weeks} weeks", "pace_note":
                "FASTER increase indicated, but no clinician faster-cadence value is set "
                "(titration_thresholds/asm_rules) - PI to specify."}
    if pace == "slower" or decision.category == RecommendationCategory.SLOWER_UPTITRATION:
        sweeks = band.slower_uptitration_interval_weeks
        if sweeks:
            return {"pace": "slower", "every_weeks": sweeks,
                    "label": f"every {sweeks} weeks (slower cadence)"}
        return {"pace": "slower", "every_weeks": weeks, "label": f"every {weeks} weeks",
                "pace_note": "SLOWER increase indicated, but no clinician slower-cadence value "
                "is set - the engine does not invent a multiplier (NEEDS_PI_SIGNOFF.md)."}
    return {"pace": "standard", "every_weeks": weeks, "label": f"every {weeks} weeks"}


def _ladder_drug_key(med: Any) -> Optional[str]:
    """Normalize a medication name to the dose_titration_ladder.json key
    (lowercase, spaces->underscores). Returns None when no medication is set."""
    if med is None:
        return None
    return str(med).strip().lower().replace(" ", "_")


def _n_up_from_guidance(decision: Decision) -> int:
    """How many dose increases the recommendation calls for (1 or 2), read from
    the clinician table's verbatim step text. Never invents a number: defaults to
    a single increase when the text does not say '2 dose increases'."""
    steps = (getattr(decision, "guidance_steps", None) or "").lower()
    if "2 dose increase" in steps or "two dose increase" in steps or "end 2 dose" in steps:
        return 2
    return 1


def _attach_ladder(schedule: Optional[Dict[str, Any]], snapshot: IntervalSnapshot,
                   decision: Decision) -> Optional[Dict[str, Any]]:
    """Attach the clinician's EXPLICIT dose ladder (Barbour final_doses v9) to the
    schedule, when a matching drug/weight-band exists. DRAFT/advisory: it does not
    change the category; it shows the exact next rung(s) and, when the next
    increase enters the higher (often-less-tolerated) range, the dagger labs to
    order. Absent/'' ladder -> schedule is returned unchanged (no regression)."""
    if schedule is None:
        return None
    drug_key = _ladder_drug_key(snapshot.medication.medication)
    comeds = snapshot.patient.concomitant_asms
    # B3 (Kristen, PI-confirmed 2026-07-16): an urgent/emergent titrating plan ("end
    # at +1/+2 dose increases HIGHER") is measured from the child's PLANNED END dose
    # on their current titration schedule (family-reported), not today's dose. Step
    # up from it when we have it; otherwise fall back to the current dose (unchanged).
    steps_text = (getattr(decision, "guidance_steps", None) or "").lower()
    planned_end = getattr(snapshot.survey, "planned_end_total_mg_per_day", None)
    from_end_dose = bool(planned_end is not None and "end" in steps_text and "higher" in steps_text)
    base_dose = planned_end if from_end_dose else snapshot.medication.total_daily_dose
    plan = dose_ladder.resolve_plan(
        drug_key, snapshot.patient.age_years, snapshot.patient.weight_kg,
        base_dose, n_up=_n_up_from_guidance(decision),
        concomitant_asms=comeds,
    )
    if plan is not None:
        plan["from_planned_end_dose"] = from_end_dose
        if from_end_dose:
            plan["planned_end_dose_mg_per_day"] = planned_end
        schedule["ladder"] = plan
    else:
        # If the ladder was SUPPRESSED because the patient is on a concomitant med
        # the ladder is not transcribed for (lamotrigine + valproate / enzyme
        # inducer), tell the physician why and where the safe regimen lives, rather
        # than silently omitting it. (asm_rules-based ceiling/steps above already
        # used the conmed-specific band.)
        reason = dose_ladder.conmed_suppression_reason(drug_key, comeds)
        if reason:
            schedule["ladder_suppressed"] = {
                "reason": "concomitant_med_restriction",
                "regimen": reason["regimen"],
                "note": reason["note"],
            }
    return schedule


def build_titration_schedule(
    snapshot: IntervalSnapshot, decision: Decision, asm_rule: Optional[ASMRule],
    cfg=None,
) -> Optional[Dict[str, Any]]:
    """Public entry: the asm_rules-based schedule, PLUS the clinician's explicit
    dose ladder (Barbour final_doses v9) attached under key 'ladder' when a
    matching drug/weight-band exists."""
    return _attach_ladder(
        _build_titration_schedule_core(snapshot, decision, asm_rule, cfg),
        snapshot, decision)


def _build_titration_schedule_core(
    snapshot: IntervalSnapshot, decision: Decision, asm_rule: Optional[ASMRule],
    cfg=None,
) -> Optional[Dict[str, Any]]:
    if decision.category not in (RecommendationCategory.ESCALATE,
                                 RecommendationCategory.SLOWER_UPTITRATION):
        return None
    if asm_rule is None:
        return {"status": "unavailable", "note": DOSING_DATA_REQUIRED}
    faster_days_global = cfg.faster_cadence_interval_days if cfg is not None else None

    wt = snapshot.patient.weight_kg
    band = asm_rule.band_for(snapshot.patient.age_years, wt,
                             snapshot.patient.concomitant_asms)
    current = snapshot.medication.total_daily_dose
    if band is None or current is None:
        return {"status": "unavailable", "note": DOSING_DATA_REQUIRED}

    step = band.uptitration_step_mg(wt)          # weight-based or fixed (clinician value)
    ceiling = band.ceiling_mg_per_day(wt)        # weight-based or fixed (clinician value)
    if step is None:
        return {"status": "unavailable", "note": DOSING_DATA_REQUIRED}
    if step <= 0:
        return {"status": "unavailable",
                "note": "Clinician-supplied uptitration step must be > 0 mg."}

    cadence = _cadence(band, decision, faster_days_global)
    after = cadence.get("every_days") and f"{cadence['every_days']} days" or \
        (f"{cadence.get('every_weeks')} weeks" if cadence.get("every_weeks") else None)

    # E7: the current dose is already AT/ABOVE the clinician ceiling. Returning an
    # empty step list with status "ok" hid exactly the over-ceiling SAFETY case.
    # Surface it explicitly (no dose numbers invented; never propose above ceiling).
    if ceiling is not None and current >= ceiling:
        note = ("Current dose is at or above the clinician-supplied ceiling "
                f"({round(ceiling, 2)} mg/day); no further increase is scheduled. "
                "Physician review required for the flagged escalation.")
        if not band.verified:
            note += " DRAFT dosing values - unverified (NEEDS_PI_SIGNOFF.md)."
        return {
            "status": "at_or_above_ceiling",
            "dose_basis": band.dose_basis,
            "current_total_mg_per_day": round(current, 2),
            "ceiling_mg_per_day": round(ceiling, 2),
            "step_mg_per_day": round(step, 2),
            "cadence": cadence,
            "steps": [],
            "verified": band.verified,
            "note": note,
        }

    steps: List[Dict[str, Any]] = []
    dose = current
    freq = snapshot.medication.frequency_per_day or band.frequency_per_day or 0
    safety_cap = 12  # bound the loop only (not a clinical value)
    while ceiling is not None and dose < ceiling and len(steps) < safety_cap:
        dose = min(dose + step, ceiling)
        steps.append({
            "step": len(steps) + 1,
            "target_total_mg_per_day": round(dose, 2),
            "per_dose_mg": round(dose / freq, 2) if freq else None,
            "after_each": after,
        })
        if dose >= ceiling:
            break
    if ceiling is None:                # no max supplied -> single next step only
        steps.append({
            "step": 1,
            "target_total_mg_per_day": round(current + step, 2),
            "per_dose_mg": round((current + step) / freq, 2) if freq else None,
            "after_each": after,
        })

    note = "Steps use clinician-supplied dose step/ceiling (weight-based where applicable)."
    if not band.verified:
        note += " DRAFT dosing values - unverified (NEEDS_PI_SIGNOFF.md)."
    if cadence.get("pace_note"):
        note += " " + cadence["pace_note"]
    return {
        "status": "ok",
        "dose_basis": band.dose_basis,
        "current_total_mg_per_day": round(current, 2),
        "ceiling_mg_per_day": round(ceiling, 2) if ceiling is not None else None,
        "step_mg_per_day": round(step, 2),
        "cadence": cadence,
        "steps": steps,
        "verified": band.verified,
        "note": note,
    }


