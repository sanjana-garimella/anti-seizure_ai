def build_decision_provenance(snapshot, decision, asm_rule, cfg=None,
                              engine_version=None):
    """Assemble a structured record of HOW the decision was formed and the
    SOURCES behind it, so a physician can verify every value. Pure read-only:
    rules that fired + the provenance/verified flag of each clinician-supplied
    input the engine consulted. No clinical values are invented here."""
    rules_fired = [{"rule": r.get("rule"), "description": r.get("description"),
                    "inputs": r.get("inputs", {})} for r in (decision.rationale or [])]

    # Dosing source (clinician-supplied ASM rule + band actually selected)
    if asm_rule is not None:
        regimen = asm_rule.selected_regimen(snapshot.patient.concomitant_asms)
        band = asm_rule.band_for(snapshot.patient.age_years, snapshot.patient.weight_kg,
                                 snapshot.patient.concomitant_asms)
        dosing = {"available": True, "medication": asm_rule.medication}
        if band is not None:
            dosing.update({
                "band_label": band.label,
                "source": getattr(band, "source", None),
                "verified": bool(getattr(band, "verified", False)),
                "ceiling_mg_per_day": band.ceiling_mg_per_day(snapshot.patient.weight_kg),
                "note": ("DRAFT dosing - unverified (clinician sign-off pending, "
                         "NEEDS_PI_SIGNOFF.md)" if not getattr(band, "verified", False)
                         else "Verified clinician value."),
            })
            if regimen is not None:
                # conmed_dependent_titration drug (lamotrigine): record which
                # concomitant-med regimen drove band selection so the physician
                # can confirm it (DRAFT - regimen selection pending PI sign-off).
                dosing["conmed_regimen"] = regimen
                dosing["conmed_regimen_note"] = (
                    "Band selected by concomitant-med regimen, not age/weight; "
                    "confirm concomitant meds. DRAFT - unverified.")
        else:
            dosing["note"] = "No dose band matches this age/weight; no dose numbers generated."
    else:
        dosing = {"available": False,
                  "note": "No clinician dosing data loaded for this medication; "
                          "category + rationale only, no dose numbers."}

    # Threshold source (seizure duration/frequency, danger, follow-up cadence)
    sections = sorted({s for r in rules_fired
                       for s in _RULE_THRESHOLD_SECTIONS.get(r.get("rule") or "", [])})
    thresholds = {
        "source": (cfg.source if cfg is not None else None),
        "verified": (bool(cfg.verified) if cfg is not None else False),
        "sections_used": sections,
        "note": "Seizure duration/frequency + danger thresholds are clinician-supplied "
                "(titration_thresholds.json); DRAFT until PI sign-off.",
    }

    # Drug facts the engine consulted (only the ones that are set)
    drug_facts = {}
    if asm_rule is not None:
        for attr in ("treats_only", "avoid_if_seizure_type", "avoid_if_comorbidity",
                     "no_switch_targets"):
            val = getattr(asm_rule, attr, None)
            if val:
                drug_facts[attr] = list(val)
        for attr in ("sjs_risk", "requires_lab_monitoring", "conmed_dependent_titration"):
            if getattr(asm_rule, attr, False):
                drug_facts[attr] = True

    # E5: thread a real engine version into provenance. Prefer an explicit
    # argument; fall back to a version carried on the decision (if ever set).
    # Previously this read decision.engine_version, which never existed -> null.
    return {
        "engine_version": engine_version or getattr(decision, "engine_version", None),
        "rules_fired": rules_fired,
        "dosing": dosing,
        "thresholds": thresholds,
        "drug_facts": drug_facts,
        "data_provenance": ("Dosing drafted from RxNorm + FDA prescribing information "
                            "(pulled 2026-06) and Dr. Barbour's 2026-06 review; compared to the "
                            "FDA label in FDA_DOSING_REFERENCE.md. All values verified:false "
                            "pending line-by-line PI sign-off."),
        "external_sources": [],   # filled by the app when it looks up FAERS/PubMed/etc.
    }


