# ---------------------------------------------------------------------------
# Note layout. The physician note is a FIXED set of sections in a FIXED order,
# so a reviewer always finds the same kind of fact in the same place:
#
#   1. Medication and dose  2. Seizures   3. Side effects   4. Family report
#   5. Recommendation       6. Safety     7. Checks
#
# A section with no content for a given case is omitted and the numbering closes
# up. There are exactly two body levels - a bullet ("  - ") and one level of
# continuation detail ("      ") - because the note renders in a `pre-wrap`
# block, where a wrapped line loses its indent; deeper nesting reads as noise.
# Safety lines carry the "  ! " lead so they stand out at a glance.
# ---------------------------------------------------------------------------
SUMMARY_SECTIONS = ("Medication and dose", "Seizures", "Side effects",
                    "Family report", "Recommendation", "Safety", "Checks")
_BULLET = "  - "
_DETAIL = "      "
_DETAIL_BULLET = "      - "
_ALERT = "  ! "


class _Note:
    """Accumulates the note's fixed sections, then renders them numbered.

    Callers add lines by section NAME rather than appending to one flat list, so
    the rendered order is the order in SUMMARY_SECTIONS no matter what order the
    builder happens to compute things in.
    """

    def __init__(self, *header: str) -> None:
        self._header: List[str] = [h for h in header if h]
        self._sections: Dict[str, List[str]] = {k: [] for k in SUMMARY_SECTIONS}
        self._footnotes: List[str] = []

    def add(self, section: str, text: str, lead: str = _BULLET) -> None:
        self._sections[section].append(lead + text)

    def detail(self, section: str, text: str) -> None:
        self.add(section, text, lead=_DETAIL)

    def alert(self, section: str, text: str) -> None:
        self.add(section, text, lead=_ALERT)

    def footnote(self, text: str) -> None:
        """A note-level statement rendered once in the closing block, above the
        physician-review notice. Used for provenance that would otherwise have to
        be repeated on every value it covers."""
        if text not in self._footnotes:
            self._footnotes.append(text)

    def has(self, section: str) -> bool:
        return bool(self._sections[section])

    def render(self) -> str:
        out = list(self._header)
        n = 0
        for name in SUMMARY_SECTIONS:
            body = self._sections[name]
            if not body:
                continue
            n += 1
            out += ["", f"{n}. {name.upper()}"] + body
        for f in self._footnotes:
            out += ["", f]
        out += ["", REVIEW_NOTICE]
        return "\n".join(out)


def append_summary_check(summary: str, label: str, text: str) -> str:
    """Add a post-engine check line to the note's CHECKS section, creating the
    section (with the next section number) when it is not there yet.

    api.py runs two checks AFTER build_clinical_summary returns (unrecognized
    medication, switch drug-family). They used to be string-concatenated onto the
    end of the note, which put them BELOW the closing physician-review notice,
    outside any section, where they were easy to miss. They now land in their own
    section and the review notice stays last.
    """
    import re
    line = f"{_BULLET}{label}: {text}"
    lines = summary.split("\n")
    if REVIEW_NOTICE not in lines:            # unexpected shape: do not lose the check
        return summary + "\n" + line
    notice = lines.index(REVIEW_NOTICE)
    end = notice - 1 if notice > 0 and lines[notice - 1] == "" else notice
    if any(ln.endswith(". CHECKS") for ln in lines):
        lines[end:end] = [line]               # CHECKS is the last section, so append
    else:
        # Number from the highest section number present (not a count), so the
        # numbering stays right even if the note's shape ever changes.
        nums = [int(mo.group(1)) for mo in
                (re.match(r"^(\d+)\. [A-Z]", ln) for ln in lines) if mo]
        lines[end:end] = ["", f"{max(nums, default=0) + 1}. CHECKS", line]
    return "\n".join(lines)


def build_clinical_summary(
    snapshot: IntervalSnapshot, status: PatientStatus, decision: Decision,
) -> str:
    """A plain-English between-visit summary for the physician, laid out as the
    fixed numbered sections of SUMMARY_SECTIONS: medication and dose · seizures ·
    side effects · family report · recommendation · safety · checks. Sections with
    nothing to say for a case are omitted; the order never varies, so a reviewer
    always finds the same kind of fact in the same place. (The machine-readable
    rule trace lives in the Recommendation's `rationale` for the audit log; this
    note reads in clinical English.)"""
    p, m, s = snapshot.patient, snapshot.medication, snapshot.survey
    age = f"{p.age_years:g} yr" if p.age_years is not None else "age not recorded"
    wt = f"{p.weight_kg:g} kg" if p.weight_kg is not None else "weight not recorded"
    med = (m.medication or "medication").replace("_", " ").title()

    DOSE, SZ, SFX, FAM, REC, SAFE = SUMMARY_SECTIONS[:6]
    note = _Note("BETWEEN-VISIT SUMMARY",
                 f"Patient {p.external_id} · {age} · {wt} · Medication: {med}")

    # -- 1. Medication and dose ---------------------------------------------
    # Kristen 2026-08-04: the dose reference reads as THREE bullets in the same
    # units, so the reported dose can be compared against the two ceilings by
    # eye - current dose · typical range · absolute max. The fields, their order
    # and their labels come from dose_ladder.dose_reference_parts(), the one
    # definition shared with the inbox card, the ladder card and the reference
    # table, so these surfaces cannot drift.
    #
    # The reference is clinician-only (physician report; NEVER the family message)
    # and resolved for THIS child's age/weight from Dr. Barbour's dosing table.
    # Values are clinician-supplied (verified:false); nothing is invented here.
    ref = dose_ladder.reference_for(_ladder_drug_key(m.medication),
                                    p.age_years, p.weight_kg, p.concomitant_asms)
    suppressed = bool((ref or {}).get("conmed_suppressed"))
    parts = dict((key, value) for key, _lbl, value in dose_ladder.dose_reference_parts(
        ref, weight_kg=p.weight_kg, current_mg_per_day=m.total_daily_dose))

    # Bullet 1, current dose: mg/day, plus mg/kg/day when the band is weight-based.
    # No per-dose x frequency restatement (Kristen 2026-08-04) - the total daily dose
    # is what the ceilings are compared against. Falls back to the long-form reported
    # dose when the mg total can't be computed (e.g. a liquid with no strength), so
    # the physician still sees what the family entered rather than nothing.
    # No ladder band (unrecognized/unbanded medicine) still gets the mg/day form -
    # just without mg/kg/day, which only a weight-based band licenses.
    _cur_s = parts.get("current") or dose_ladder.dose_value_str(m.total_daily_dose)
    note.add(DOSE, f"Current dose: {_cur_s or _dose_line(m)}")

    if suppressed:
        note.add(DOSE, "Typical range and absolute max: the standard table does not apply "
                 f"with the current concomitant medicine ({humanize(ref.get('regimen'))}); "
                 "use the concomitant-med-specific regimen. DRAFT, clinician to confirm.")
    else:
        # Bullets 2 and 3, the two ceilings. Kept as separate fields (not one
        # number) so the top of the typical range is never read as the hard max.
        if parts.get("typical_range"):
            note.add(DOSE, f"Typical range: {parts['typical_range']}")
        if parts.get("absolute_max"):
            note.add(DOSE, f"Absolute max: {parts['absolute_max']}")
        if parts.get("typical_range") or parts.get("absolute_max"):
            # 2026-08-04: the per-value provenance line under the dose bullets was
            # cut for clutter. The TAG cannot simply disappear -
            # NON_NEGOTIABLE_RULES.md §2, "never present unverified dosing as
            # authoritative, always tag provenance", and this note is EHR-ready text
            # that leaves the app. So it moves to a single note-level footnote
            # instead of repeating under every value (the same "say it once"
            # principle already applied to the /review page's draft badges).
            note.footnote("Dose range and maximum are DRAFT, unverified values from "
                          "Dr. Barbour's dosing table; the clinician confirms them.")
        # #9 headroom cue: is a switch premature? Show whether the current dose
        # still has room to climb toward the usual effective max, or is at/above
        # it (escalation nearly exhausted -> a switch or add-on is reasonable).
        _cur = m.total_daily_dose
        _effmax = (ref or {}).get("effective_max_mg_per_day")
        if _cur is not None and isinstance(_effmax, (int, float)):
            if _cur >= _effmax:
                note.detail(DOSE, "Headroom: at/above the usual effective max "
                            f"(~{_effmax:g} mg/day) - little room to increase.")
            else:
                note.detail(DOSE, "Headroom: below the usual effective max "
                            f"(~{_effmax:g} mg/day) - room to increase.")
        # Reported "at goal" but the dose is below the table's typical range:
        # surface the mismatch instead of leaving two facts that disagree.
        _minm = (ref or {}).get("min_maintenance_mg_per_day")
        if (status.at_goal and _cur is not None and isinstance(_minm, (int, float))
                and _cur < _minm):
            note.detail(DOSE, f"Check: reported at the goal dose, but {_cur:g} mg/day is "
                        f"below the typical range (starts ~{_minm:g} mg/day) - confirm the "
                        "goal dose.")

    note.add(DOSE, "Dose goal status: " + ("at the goal dose" if status.at_goal
                                            else humanize(status.dose_goal_status.value)))
    note.add(DOSE, f"Adherence: {humanize(status.adherence.value, ADHERENCE_HUMAN)}"
             + (f" (reasons given: {humanize_list(s.missed_dose_reasons)})"
                if s.missed_dose_reasons else ""))

    # -- 2. Seizures --------------------------------------------------------
    if s.seizure_control == SeizureControl.BREAKTHROUGH:
        # Kristen §2 (2026-07): breakthrough description with the urgency tier, the
        # overall frequency + trend, recency, medicine-in-the-2-days, and a per-type
        # breakdown (type · duration · frequency · responsiveness) when episode-level
        # detail was captured. Duration is what separates non-urgent from urgent, so
        # the block says so explicitly when duration is missing.
        # Tier vocabulary is non_urgent | urgent | emergent. Hyphenate rather than
        # printing the raw token: "NON_URGENT" reads like a code identifier in a
        # physician note, and an underscore also broke the review page's tier badge.
        #
        # Read the tier from the DECISION first (that is the tier the recommendation
        # was actually taken from, including the one path that deliberately forces
        # "urgent"), and fall back to the CLASSIFIER's tier. Without the fallback the
        # tier only ever printed on the breakthrough-table path: a non-urgent
        # breakthrough showed none, and so did an EMERGENT one (whole-body >3 min
        # routes through the danger rule), which is exactly where the reviewer most
        # needs it. Display only - the tier is a description of the breakthrough and
        # is not re-deciding anything.
        tier = (getattr(decision, "urgency_tier", None)
                or getattr(status, "breakthrough_tier", None))
        note.add(SZ, "Breakthrough seizures (family-reported)"
                 + (f". Urgency tier: {tier.replace('_', '-').upper()}" if tier else ""))
        trend = (humanize(getattr(s.seizure_trend, "value", None), _TREND_HUMAN)
                 if s.seizure_trend else "")
        # Kristen v2 review (case B2): don't print "number not given" when the
        # per-type lines below already state how often each seizure type occurs.
        _ep_freq = any(e and (e.get("frequency_bucket") or e.get("frequency"))
                       for e in (s.seizure_episodes or []))
        if s.seizure_count is not None:
            note.add(SZ, f"Overall frequency: {s.seizure_count} "
                     f"{humanize(s.seizure_count_unit)}".strip()
                     + (f", trend: {trend}" if trend else ""))
        elif not _ep_freq:
            note.add(SZ, "Overall frequency: number not given"
                     + (f", trend: {trend}" if trend else ""))
        elif trend:
            note.add(SZ, f"Trend: {trend}")
        if s.most_recent_seizure_date:
            note.add(SZ, "Most recent: "
                     + _LAST_HUMAN.get(s.most_recent_seizure_date, str(s.most_recent_seizure_date)))
        if s.on_medication_2days_prior is not None:
            note.add(SZ, "Taking medicine in the 2 days before: "
                     + ("yes" if s.on_medication_2days_prior else "no (doses were missed)"))
        eps = [e for e in (s.seizure_episodes or []) if e]
        if eps:
            note.add(SZ, "By type:")
            for i, ep in enumerate(eps, start=1):
                looks = _seizure_type_label(ep.get("look"))
                resp = ""
                if ep.get("unresponsive") is True:
                    resp = ", unresponsive during seizure"
                elif ep.get("unresponsive") is False:
                    resp = ", responsive during seizure"
                parts = ["lasting " + _DUR_HUMAN.get(ep["duration"], str(ep["duration"]))
                         if ep.get("duration") else "length not captured"]
                if ep.get("frequency_bucket"):
                    parts.append("occurring " + _FREQ_BUCKET_SHORT.get(
                        ep["frequency_bucket"], str(ep["frequency_bucket"])))
                elif ep.get("frequency"):
                    parts.append(
                        f"occurring {ep['frequency']} {humanize(ep.get('frequency_unit'))}".strip())
                # One line per seizure type, not three: type, responsiveness, then
                # length and frequency. Deeper nesting did not survive the wrap.
                note.add(SZ, f"{i}) {looks}{resp}, " + ", ".join(parts), lead=_DETAIL)
        else:
            types = humanize_list(s.seizure_types, SEIZURE_TYPE_HUMAN)
            if types:
                note.add(SZ, f"Type(s): {types}")
            if getattr(s, "seizure_duration", None):
                note.add(SZ, "Typical length: "
                         + _DUR_HUMAN.get(s.seizure_duration, str(s.seizure_duration)))
        if not getattr(status, "duration_captured", True):
            note.alert(SZ, "Seizure duration was not captured. Duration is what separates "
                       "non-urgent from urgent; confirm with the family before finalizing "
                       "the tier.")
    else:
        note.add(SZ, "None reported this interval")
    # Triggers sit with the seizures they preceded, not in the general family report.
    if getattr(s, "seizure_triggers", None):
        allnote = ""
        if status.triggers_all_episodes is True:
            allnote = " (present before ALL breakthrough seizures)"
        elif status.triggers_all_episodes is False:
            allnote = " (not present before all seizures)"
        note.add(SZ, f"Possible triggers: {humanize_list(s.seizure_triggers)}{allnote}")

    # -- 3. Side effects ----------------------------------------------------
    if status.side_effects_present or s.side_effects_other:
        listed = humanize_list(s.side_effects_present, SIDE_EFFECT_HUMAN)
        if s.side_effects_other:
            listed = (listed + ", " if listed else "") + f"other: \"{s.side_effects_other}\""
        note.add(SFX, f"Reported: {listed or 'reported'}"
                 f", overall {humanize(status.side_effect_severity.value)}")
        # Kristen's side-effect LEVEL (L0-L5) is what indexes her decision tables, so
        # the reviewer should see the same number the rule used. A sweep of 5400 cases
        # found it reached the note in only some of them, and then only incidentally,
        # embedded in the one-line Reason (e.g. "... titrating, L1 ..."). Read from the
        # classifier, which always sets it; display only.
        _lvl = getattr(status, "side_effect_level", None)
        if isinstance(_lvl, int):
            note.add(SFX, f"Side-effect level: L{_lvl} (Barbour scale, 0 to 5)")
        if s.rash_severity:
            note.add(SFX, f"Rash: {humanize(s.rash_severity.value, RASH_HUMAN)}")
        if s.impact_scale:
            note.add(SFX, f"Impact on daily life: {humanize(s.impact_scale, IMPACT_HUMAN)}")
    else:
        note.add(SFX, "None reported")

    # -- 4. Family report ---------------------------------------------------
    if s.overall_change:
        note.add(FAM, "Overall, the family feels things are: "
                 f"{humanize(s.overall_change.value, OVERALL_HUMAN)}")
    note.add(FAM, f"Preference: {humanize(status.family_preference.value, PREFERENCE_HUMAN)}")
    if getattr(s, "med_pref_rank", None):
        _PREF_DIR = {"increase": "increase the current medicine", "add": "add a second medicine",
                     "switch": "switch to a different medicine"}
        ranked = " > ".join(humanize(r, _PREF_DIR) for r in s.med_pref_rank)
        strength = f" (feels {humanize(s.med_pref_strength)})" if s.med_pref_strength else ""
        note.add(FAM, f"If a change is needed, prefers: {ranked}{strength}")
    if s.free_text:
        note.add(FAM, f"In their words: \"{s.free_text}\"")

    # -- 5. Recommendation --------------------------------------------------
    step_label = category_label(decision.category.value)
    if decision.pace == "faster":
        step_label += ", FASTER than the standard cadence"
    elif decision.pace == "slower":
        step_label += ", more SLOWLY than standard"
    note.add(REC, f"Suggested step: {step_label}")
    # One-line reason first (Barbour T15: physician can agree/disagree quickly).
    if decision.reason_summary:
        note.add(REC, f"Reason: {decision.reason_summary}")
    # (Kristen v2 review, D1) A no-change recommendation gets a concise draft: the
    # verbose lines below (do-not-switch list, "Why this is suggested", adherence
    # restatement) are dropped ONLY for no-change and kept for escalate/switch/add,
    # where they carry real information. All remain in the structured output.
    _concise = (decision.category.value == "no_change")
    if decision.switch_target:
        note.add(REC, f"Possible switch target: {humanize(decision.switch_target)}")
        # Dr. Barbour's week-by-week starting schedule for the new medicine (v9
        # '<Drug> Initiation' tabs) - display only, her cells verbatim; defers when
        # the band is unclear or the tab doesn't apply. Taper of the old medicine is
        # NOT shown: pending her answer (NEEDS_PI_SIGNOFF #69).
        _sched = initiation.schedule_for(decision.switch_target, p.age_years, p.weight_kg,
                                         p.concomitant_asms)
        note.add(REC, f"Starting schedule for {humanize(decision.switch_target)} "
                 "(Dr. Barbour's initiation tab, DRAFT):")
        for _l in initiation.schedule_lines(_sched):
            note.detail(REC, _l)
    if decision.category.value == "switch_medication" and not decision.switch_target:
        note.add(REC, "Switch target: for the physician to choose (no chart-approved option). "
                 "A switch-candidate menu is a planned feature.")
    if decision.switch_exclusions and not _concise:
        note.add(REC, "Do NOT switch to: " + humanize_list(decision.switch_exclusions)
                 + " (already tried, or a worse-tolerated option).")
    # (dedupe 2026-07-23) the urgency tier + verbatim steps already ride in the one-line
    # "Reason:" above (e.g. "Breakthrough (urgent, titrating, L0): quicken ..."), so the
    # separate "tier" and "Steps" lines were removed to cut the repetition Kristen flagged.
    # (guidance_steps is still consumed below for the planned-end "+N higher" block.)
    # B3 (Kristen, PI-confirmed 2026-07-16): when the plan is "end +N higher" and the
    # family reported the dose they are building up to, show that end dose and the
    # computed target (N rungs up the clinician ladder). DRAFT - clinician confirms.
    _b3_steps = (getattr(decision, "guidance_steps", None) or "").lower()
    _b3_end = getattr(s, "planned_end_total_mg_per_day", None)
    if _b3_end is not None and "end" in _b3_steps and "higher" in _b3_steps:
        _b3_n = _n_up_from_guidance(decision)
        _b3_plan = dose_ladder.resolve_plan(
            _ladder_drug_key(m.medication), p.age_years, p.weight_kg, _b3_end,
            n_up=_b3_n, concomitant_asms=p.concomitant_asms)
        if _b3_plan and _b3_plan.get("next_up"):
            _b3_tgt = _b3_plan["next_up"][-1].get("target_mg_per_day")
            note.add(REC, f"Planned end dose (family-reported): {_b3_end:g} mg/day -> end "
                     f"+{_b3_n} higher = ~{_b3_tgt:g} mg/day (DRAFT - clinician to confirm).")
        else:
            note.add(REC, f"Planned end dose (family-reported): {_b3_end:g} mg/day -> end "
                     f"+{_b3_n} higher (reaches the maximum - clinician to set the exact dose).")
    # Tablet / liquid amounts for the ladder step(s) the family would take (the SAME
    # steps the family message names). Display only - Dr. Barbour's conversion
    # rules (data/formulation_rules.json); never changes the decision or ceiling.
    _steps_txt = (getattr(decision, "guidance_steps", None) or "").lower()
    if (decision.category == RecommendationCategory.ESCALATE
            or (decision.category == RecommendationCategory.HOLD
                and ("after week 2" in _steps_txt or "weeks 1-2 stay" in _steps_txt))):
        _up = _family_up_plan(snapshot, decision)
        _tg, _rows = _formulation_rows(snapshot, decision, _up)
        if _tg:
            note.add(REC, "Next dose (Dr. Barbour's ladder): " + "; ".join(
                f"step {i} {dose_ladder.dose_value_str(t, p.weight_kg, True)}"
                for i, t in enumerate(_tg, start=1)))
            _on_tabs = (m.dose_unit or "") == "tablets"
            for _r in _rows:
                _pre = f"Step {_r['step']}: " if len(_rows) > 1 else ""
                if _r["tablet_text"]:
                    note.detail(REC, f"{_pre}{_r['tablet_text']}")
                if _r["notes"]:              # one short line (e.g. "no tablet fits" + skip-ahead)
                    note.detail(REC, f"{_pre}" + " ".join(_r["notes"]))
                if _r["liquid_text"]:
                    _lbl = ("liquid alternative"
                            if (_on_tabs and not _r["tablet_text"] and not _r.get("age_rule_form"))
                            else "liquid")
                    note.detail(REC, f"{_pre}{_lbl}: {_r['liquid_text']}")
            if any(_r["tablet_text"] or _r["liquid_text"] for _r in _rows):
                note.footnote("Tablet/liquid amounts are a DRAFT conversion of the ladder dose "
                              "(Dr. Barbour's -10%/+30% rules, unverified); the clinician "
                              "confirms them.")
    if getattr(decision, "lab_orders", None):
        note.add(REC, "Labs to order (per medication): " + ", ".join(decision.lab_orders) + ".")
    if getattr(decision, "dosing_note", None):
        note.add(REC, f"Dosing note: {decision.dosing_note}")
    if decision.followup_weeks:
        note.add(REC, "Recommended follow-up: schedule another digital check-in in "
                 f"~{decision.followup_weeks} week(s).")
    if getattr(decision, "family_prompt", None):
        note.add(REC, "Question to put to the family (PI-supplied wording):")
        note.detail(REC, f"“{decision.family_prompt}”")
    # (Kristen v2 review, D1) On a no-change recommendation the "Why this is
    # suggested" block and the "Note on adherence" line are dropped as verbose
    # (the one-line "Reason:" conveys the why; both remain in the structured
    # output). On escalate/switch/add they are kept.
    reasons = human_reasons(decision.rationale)
    if reasons and not _concise:
        # Drop any reason the one-line "Reason:" above already states verbatim
        # (Kristen flagged the repetition); the full set stays in `rationale`.
        _said = (decision.reason_summary or "").strip().lower()
        reasons = [r for r in reasons if not (_said and r.strip().lower() in _said)]
    if reasons and not _concise:
        note.add(REC, "Why this is suggested:")
        for r in reasons:
            note.add(REC, r, lead=_DETAIL_BULLET)
    if decision.adherence_note and not _concise:
        note.add(REC, f"Note on adherence: {decision.adherence_note}")

    # -- 6. Safety ----------------------------------------------------------
    # All safety content in one place, so a reviewer never has to hunt for it.
    if decision.safety_concern_flag:
        note.alert(SAFE, "An urgent safety concern was flagged - a physician must review "
                   "right away, and no message goes to the family automatically.")
    for fl in decision.urgent_flags:
        note.add(SAFE, humanize(fl, URGENT_FLAG_HUMAN))
    # Safety notes surface to the physician. EXCEPTION (Kristen v2 review, D1 -
    # PI-directed): on a no-change continuation, drop the "consider HLA-B*1502
    # screening before/around use" advisory - it is not actionable when nothing is
    # being started or switched. It STAYS in the structured safety_notes output
    # (audit) and still renders on escalate/switch/add (e.g. switching TO
    # oxcarbazepine). All other safety notes are always shown.
    for sn in (decision.safety_notes or []):
        if _concise and "HLA-B*1502" in sn:
            continue
        note.alert(SAFE, sn)

    return note.render()


