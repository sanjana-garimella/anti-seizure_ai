def _dose_line(m):
    """Reported dose as a sentence, converting tablets/mL to mg when a strength
    is given; says so plainly when mg cannot be computed."""
    amt, unit, freq = m.dose_amount, (m.dose_unit or "mg"), m.frequency_per_day
    if (amt is None or not freq or not isinstance(amt, (int, float))
            or not isinstance(freq, (int, float))):
        return "not reported"
    total = m.total_daily_dose
    if unit == "mg":
        return f"{amt:g} mg x {freq}/day = {total:g} mg/day"
    # E9: use the shared conversion helper (single source of truth).
    per = per_dose_mg(amt, unit, m.concentration)
    if per is not None and total is not None and isinstance(m.concentration, (int, float)):
        return (f"{amt:g} {unit} of {m.concentration:g} mg = {per:g} mg per dose, "
                f"{freq}/day = {total:g} mg/day")
    return f"{amt:g} {unit} x {freq}/day (mg total not computable, strength not given)"


